import { createServer } from 'vite';
import { mkdir, writeFile, readFile, readdir, unlink } from 'node:fs/promises';
const selectedEras = process.argv
  .filter((argument) => argument.startsWith('--era='))
  .map((argument) => argument.slice(6));
const server = await createServer({
  server: { middlewareMode: true, watch: null },
  optimizeDeps: { noDiscovery: true, include: [] },
  appType: 'custom',
});
try {
  const { generateFootprints } = await server.ssrLoadModule('/scripts/footprint-generator.js');
  const data = await generateFootprints({ eras: selectedEras.length ? selectedEras : null });
  const directory = new URL('../src/data/generated/', import.meta.url);
  await mkdir(directory, { recursive: true });
  const families = {};
  for (const [key, index] of Object.entries(data.keys)) {
    const era = key.split('|')[2];
    families[era] ??= {
      keys: {},
      shapes: [],
      solids: [],
      shapeMap: new Map(),
      solidMap: new Map(),
    };
    const family = families[era];
    if (!family.shapeMap.has(index)) {
      const shape = data.shapes[index].map((s) => {
        const compact = [s.cx, s.cz, s.halfW, s.halfD, s.yMin, s.yMax];
        if (s.points) compact.push(s.points);
        const signature = JSON.stringify(compact);
        if (!family.solidMap.has(signature)) {
          family.solidMap.set(signature, family.solids.length);
          family.solids.push(compact);
        }
        return family.solidMap.get(signature);
      });
      family.shapeMap.set(index, family.shapes.length);
      family.shapes.push(shape);
    }
    family.keys[key] = family.shapeMap.get(index);
  }
  let bytes = 0;
  // Scoped authoring updates only existing families. A complete generation owns
  // the manifest, loaders and the all-era mine clearance union.
  const familyNames = selectedEras.length
    ? JSON.parse(await readFile(new URL('buildingFootprints.json', directory), 'utf8')).families
    : Object.keys(families);
  if (selectedEras.some((era) => !familyNames.includes(era)))
    throw new Error('Generate all footprint families before a scoped update');
  const expected = new Set([
    'mineClearances.json',
    'buildingFootprints.json',
    'footprintLoaders.js',
    ...familyNames.flatMap((era) =>
      ['keys', 'shapes', 'solids'].map((kind) => `footprints-${era}-${kind}.json`),
    ),
  ]);
  async function publish(name, value) {
    const text = typeof value === 'string' ? value : JSON.stringify(value);
    expected.add(name);
    const file = new URL(name, directory);
    if (process.argv.includes('--check')) {
      if ((await readFile(file, 'utf8')) !== text)
        throw new Error(`${name} drifted: run npm run assets:footprints`);
    } else await writeFile(file, text);
    bytes += text.length;
  }
  for (const [era, { keys, shapes, solids }] of Object.entries(families))
    for (const [kind, data] of Object.entries({ keys, shapes, solids }))
      await publish(`footprints-${era}-${kind}.json`, data);
  if (!selectedEras.length) {
    const powerSolids = Object.entries(data.keys)
      .filter(([key]) => key.startsWith('powerHouse|'))
      .flatMap(([, index]) => data.shapes[index]);
    await publish('mineClearances.json', {
      powerHouseHalfWidth: Math.max(...powerSolids.map((s) => -s.cx + s.halfW)),
    });
    await publish('buildingFootprints.json', { format: 2, families: Object.keys(families) });
    await publish(
      'footprintLoaders.js',
      // Fetched JSON assets, not JavaScript chunks: footprints are data, and several
      // families are larger than a chunk should be.
      `// Generated by scripts/generate-footprints.mjs.\nimport { readJsonAsset } from '../../game/town/assets/assetFiles.js';\nexport const footprintLoaders = {${Object.keys(
        families,
      )
        .map(
          (era) =>
            `${JSON.stringify(era)}: () => Promise.all([${['keys', 'shapes', 'solids']
              .map(
                (kind) =>
                  `readJsonAsset(new URL('./footprints-${era}-${kind}.json', import.meta.url))`,
              )
              .join(',')}]).then(([keys,shapes,solids])=>({keys,shapes,solids}))`,
        )
        .join(',')}};\n`,
    );
  }
  for (const name of await readdir(directory))
    if (!expected.has(name)) {
      if (process.argv.includes('--check')) throw new Error(`Orphaned generated file ${name}`);
      else await unlink(new URL(name, directory));
    }
  console.log(
    `${Object.keys(data.keys).length} keys, ${bytes} bytes across ${Object.keys(families).length} lazy footprint families`,
  );
} finally {
  await server.close();
}
