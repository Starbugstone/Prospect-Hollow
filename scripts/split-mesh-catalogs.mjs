import { mkdir, readFile, writeFile, readdir, unlink } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { encodeMeshChunk } from '../src/game/town/assets/meshChunks.js';

// The Blender exports remain authoring sources. Only bounded, lazy binary chunks enter
// Vite (see src/game/town/assets/meshChunks.js for the format).
const directory = new URL('../src/assets/meshes/', import.meta.url);
await mkdir(directory, { recursive: true });
const groups = new Map();
// City meshes load per era asset family, read from the era catalog so a new era needs no edit.
const { outputFiles } = await build({
  stdin: {
    contents:
      "import { ERAS } from './src/data/eras.js'; export default [...new Set(ERAS.map((era) => era.evolution.cityAssets).filter(Boolean))];",
    resolveDir: fileURLToPath(new URL('..', import.meta.url)),
  },
  bundle: true,
  platform: 'node',
  format: 'esm',
  write: false,
});
const { default: eras } = await import(
  `data:text/javascript;base64,${Buffer.from(outputFiles[0].text).toString('base64')}`
);
for (const source of ['city', 'future', 'leisure']) {
  const catalog = JSON.parse(
    await readFile(new URL(`../src/assets/${source}-meshes.json`, import.meta.url)),
  );
  let footprints = {};
  try {
    footprints = JSON.parse(
      await readFile(new URL(`../src/assets/${source}-meshes-footprints.json`, import.meta.url)),
    );
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  for (const [name, parts] of Object.entries(catalog.models)) {
    const era = source === 'city' && eras.find((era) => name.startsWith(`${era}-`));
    const family = era || source;
    if (!groups.has(family)) groups.set(family, []);
    groups.get(family).push([name, parts, footprints[name]]);
  }
}
const files = new Set();
const manifest = [];
for (const [family, models] of groups) {
  const chunks = [];
  let pack = {},
    footprintPack = {},
    size = 0;
  const flush = async () => {
    const file = `${family}-${chunks.length}.bin`;
    files.add(file).add(`${file}z`);
    const bytes = encodeMeshChunk({
      models: pack,
      ...(Object.keys(footprintPack).length ? { footprints: footprintPack } : {}),
    });
    await writeFile(new URL(file, directory), bytes);
    await writeFile(new URL(`${file}z`, directory), gzipSync(bytes, { level: 9 }));
    chunks.push(
      `() => loadMeshChunk(new URL('./${file}z', import.meta.url), new URL('./${file}', import.meta.url))`,
    );
    pack = {};
    footprintPack = {};
    size = 0;
  };
  for (const [name, parts, footprints] of models) {
    const bytes = JSON.stringify([parts, footprints]).length;
    if (size && size + bytes > 700_000) await flush();
    pack[name] = parts;
    if (footprints) footprintPack[name] = footprints;
    size += bytes;
  }
  if (size) await flush();
  manifest.push(`${JSON.stringify(family)}: [${chunks.join(', ')}]`);
}
await writeFile(
  new URL('loaders.js', directory),
  `// Generated by scripts/split-mesh-catalogs.mjs.\nimport { loadMeshChunk } from '../../game/town/assets/meshChunks.js';\nexport const meshLoaders = {${manifest.join(',\n')}};\n`,
);
for (const file of await readdir(directory))
  if (/\.(json|binz?)$/.test(file) && !files.has(file)) await unlink(new URL(file, directory));
