import { mkdir, readFile, writeFile, readdir, unlink } from 'node:fs/promises';

// The Blender exports remain authoring sources. Only bounded, lazy chunks enter Vite.
const directory = new URL('../src/assets/meshes/', import.meta.url);
await mkdir(directory, { recursive: true });
const groups = new Map();
const eras = ['post-war', 'aviation', 'broadcast', 'contemporary'];
for (const source of ['city', 'future', 'leisure']) {
  const catalog = JSON.parse(
    await readFile(new URL(`../src/assets/${source}-meshes.json`, import.meta.url)),
  );
  let footprints = {};
  try {
    footprints = JSON.parse(
      await readFile(new URL(`../src/assets/${source}-meshes-footprints.json`, import.meta.url)),
    );
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  for (const [name, parts] of Object.entries(catalog.models)) {
    const era = source === 'city' && eras.find((era) => name.startsWith(`${era}-`));
    const family = era || source;
    if (!groups.has(family)) groups.set(family, []);
    groups.get(family).push([name, parts, footprints[name]]);
  }
}
const files = new Set();
const manifest = [];
for (const [family, models] of groups) {
  const chunks = [];
  let pack = {},
    footprintPack = {},
    size = 0;
  const flush = async () => {
    const file = `${family}-${chunks.length}.json`;
    files.add(file);
    await writeFile(
      new URL(file, directory),
      JSON.stringify({
        models: pack,
        ...(Object.keys(footprintPack).length ? { footprints: footprintPack } : {}),
      }),
    );
    chunks.push(`() => import('./${file}')`);
    pack = {};
    footprintPack = {};
    size = 0;
  };
  for (const [name, parts, footprints] of models) {
    const bytes = JSON.stringify([parts, footprints]).length;
    if (size && size + bytes > 700_000) await flush();
    pack[name] = parts;
    if (footprints) footprintPack[name] = footprints;
    size += bytes;
  }
  if (size) await flush();
  manifest.push(`${JSON.stringify(family)}: [${chunks.join(', ')}]`);
}
await writeFile(
  new URL('loaders.js', directory),
  `// Generated by scripts/split-mesh-catalogs.mjs.\nexport const meshLoaders = {${manifest.join(',\n')}};\n`,
);
for (const file of await readdir(directory))
  if (file.endsWith('.json') && !files.has(file)) await unlink(new URL(file, directory));
